-- 4. MEMBRES D'UN GROUPE
-- (créée après group_permissions pour pouvoir y faire référence)
-- ============================================================
create table if not exists group_members (
  id bigint generated by default as identity primary key,
  group_id bigint references groups(id) on delete cascade not null,
  member_id bigint references members(id) on delete cascade not null,
  role text default 'member' check (role in ('member', 'leader')),
  joined_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(group_id, member_id)
);

alter table group_members enable row level security;

-- Admin/owner voit tout. Un responsable avec can_view voit son groupe.
create policy "Users can view group members" on group_members
  for select using (
    exists (
      select 1 from groups g
      join church_users cu on cu.church_id = g.church_id
      where g.id = group_members.group_id
      and cu.user_id = auth.uid()
      and (
        cu.role in ('admin', 'owner')
        or exists (
          select 1 from group_permissions gp
          where gp.group_id = group_members.group_id
          and gp.member_id = (
            select m.id from members m
            where m.church_id = g.church_id
            and m.email = auth.email()
            limit 1
          )
          and gp.can_view = true
        )
      )
    )
  );

create policy "Admins can insert group members" on group_members
  for insert with check (
    exists (
      select 1 from groups g
      join church_users cu on cu.church_id = g.church_id
      where g.id = group_members.group_id
