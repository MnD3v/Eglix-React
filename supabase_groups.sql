-- 3. PERMISSIONS DES RESPONSABLES
-- (créée AVANT group_members pour éviter les références circulaires)
-- ============================================================
create table if not exists group_permissions (
  id bigint generated by default as identity primary key,
  group_id bigint references groups(id) on delete cascade not null,
  member_id bigint references members(id) on delete cascade not null,
  can_view boolean default true,
  can_add boolean default false,
  can_remove boolean default false,
  can_edit boolean default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(group_id, member_id)
);

