  );


-- 5. TRIGGER updated_at
-- ============================================================
create or replace function update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end;
$$ language plpgsql;

drop trigger if exists set_groups_updated_at on groups;
create trigger set_groups_updated_at
  before update on groups
  for each row execute procedure update_updated_at_column();

drop trigger if exists set_group_permissions_updated_at on group_permissions;
create trigger set_group_permissions_updated_at
  before update on group_permissions
  for each row execute procedure update_updated_at_column();
