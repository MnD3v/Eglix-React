-- 1. TYPES DE GROUPES
-- ============================================================
create table if not exists group_types (
  id bigint generated by default as identity primary key,
  church_id bigint references churches(id) on delete cascade not null,
  name text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table group_types enable row level security;

create policy "Users can view group types of their church" on group_types
  for select using (
    exists (
      select 1 from church_users cu
      where cu.church_id = group_types.church_id
      and cu.user_id = auth.uid()
    )
  );

create policy "Admins can insert group types" on group_types
  for insert with check (
    exists (
      select 1 from church_users cu
      where cu.church_id = group_types.church_id
      and cu.user_id = auth.uid()
      and cu.role in ('admin', 'owner')
    )
  );

create policy "Admins can update group types" on group_types
  for update using (
    exists (
      select 1 from church_users cu
      where cu.church_id = group_types.church_id
      and cu.user_id = auth.uid()
      and cu.role in ('admin', 'owner')
    )
  );

create policy "Admins can delete group types" on group_types
  for delete using (
    exists (
      select 1 from church_users cu
      where cu.church_id = group_types.church_id
      and cu.user_id = auth.uid()
      and cu.role in ('admin', 'owner')
    )
  );


