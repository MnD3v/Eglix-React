-- Trigger to create profile on signup
create or replace function public.handle_new_user() 
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, new.raw_user_meta_data->>'full_name');
  return new;
end;
$$ language plpgsql security definer;

-- Drop trigger if exists to avoid duplication error on re-run
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- RPC Function for Public Member Registration
-- This function allows anyone (even unauthenticated) to insert a member into a specific church
create or replace function register_member_via_link(
  p_church_id bigint,
  p_first_name text,
  p_last_name text,
  p_gender text,
  p_phone text,
  p_email text,
  p_address text
)
returns json
language plpgsql
security definer -- Bypass RLS
as $$
declare
  new_member_id bigint;
begin
  -- Validate inputs
  if p_first_name is null or p_last_name is null then
    raise exception 'First name and last name are required';
  end if;

  -- Insert member
  insert into members (church_id, first_name, last_name, gender, phone, email, address, status)
  values (p_church_id, p_first_name, p_last_name, p_gender, p_phone, p_email, p_address, 'active')
  returning id into new_member_id;

  return json_build_object('id', new_member_id, 'success', true);
end;
$$;
